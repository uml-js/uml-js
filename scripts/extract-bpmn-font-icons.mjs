/**
 * Extracts icons from the bpmn-font SVG font into lib/core/icons/bpmn-font.js.
 *
 * Usage: node scripts/extract-bpmn-font-icons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const GLYPHS = [
  'hand-tool',
  'lasso-tool',
  'space-tool',
  'connection',
  'screw-wrench',
  'trash',
  'task',
  'gateway-none',
  'end-event-terminate',
  'start-event-none'
];

const require = createRequire(import.meta.url);

const fontPath = require.resolve('bpmn-font/dist/font/bpmn.svg');
const font = readFileSync(fontPath, 'utf8');

const paths = {};

for (const name of GLYPHS) {
  const match = new RegExp(`<glyph glyph-name="${ name }"[^>]* d="([^"]+)"`).exec(font);

  if (!match) {
    throw new Error(`glyph <${ name }> not found`);
  }

  paths[name] = match[1];
}

const content = `/**
 * Icon outlines extracted from bpmn-font (https://github.com/bpmn-io/bpmn-font),
 * Copyright (c) 2014-present, Camunda Services GmbH, licensed under the
 * SIL Open Font License, Version 1.1 (https://scripts.sil.org/OFL).
 *
 * Glyph coordinates: 1000 units per em, y axis pointing up, baseline at 0,
 * ascent 850, descent -150.
 *
 * GENERATED by scripts/extract-bpmn-font-icons.mjs, do not edit.
 */
export default ${ JSON.stringify(paths, null, 2) };
`;

writeFileSync(new URL('../lib/core/icons/bpmn-font.js', import.meta.url), content);

console.log(`extracted ${ GLYPHS.length } glyphs`);
